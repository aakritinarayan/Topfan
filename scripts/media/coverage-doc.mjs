/**
 * Writes docs/media-coverage.md from a media audit run (tests/e2e/media-audit.mjs --json) and credits.json.
 * Usage: node scripts/media/coverage-doc.mjs <audit-1512.json> [audit-1126.json] [--before before.json]
 * Every count in the doc comes from the audit files passed in; nothing is typed by hand except the notes below.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const args = process.argv.slice(2);
const beforeFile = args.includes("--before") ? args.splice(args.indexOf("--before"), 2)[1] : null;
const [mainFile, narrowFile] = args;
const main = JSON.parse(fs.readFileSync(mainFile));
const narrow = narrowFile ? JSON.parse(fs.readFileSync(narrowFile)) : null;
const before = beforeFile ? JSON.parse(fs.readFileSync(beforeFile)) : null;
const credits = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/media/credits.json")));
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, "src/media/assets.json")));

const byFile = Object.fromEntries(Object.entries(credits).map(([k, c]) => [`/${c.file}`, { key: k, ...c }]));
const gcd = (a, b) => (b ? gcd(b, a % b) : a);
const ratio = (w, h) => { const g = gcd(w, h); const r = `${w / g}:${h / g}`; return r.length > 7 ? (w / h).toFixed(2) + ":1" : r; };
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const issueCount = (r) => r.empty.length + r.avatars + r.broken.length + r.noPoster + r.noSrc + r.stretched + (r.fallbacks ?? 0) + r.failed.length;
const sum = (rows, f) => rows.reduce((n, r) => n + f(r), 0);
const summary = (rows) => ({
  routes: rows.length,
  clean: rows.filter((r) => !issueCount(r)).length,
  images: sum(rows, (r) => r.images),
  players: sum(rows, (r) => r.players?.length ?? 0),
  empty: sum(rows, (r) => r.empty.length),
  avatars: sum(rows, (r) => r.avatars),
  broken: sum(rows, (r) => r.broken.length),
  stretched: sum(rows, (r) => r.stretched),
  fallbacks: sum(rows, (r) => r.fallbacks ?? 0),
  failed: sum(rows, (r) => r.failed.length),
  overflow: rows.filter((r) => r.overflow).length,
});
const S = summary(main), N = narrow && summary(narrow), B = before && summary(before);

const out = [];
const w = (s = "") => out.push(s);
w("# Media coverage");
w();
w(`Generated by \`scripts/media/coverage-doc.mjs\` from an automated audit (\`tests/e2e/media-audit.mjs\`) on ${new Date().toLocaleDateString("en-CA")}. The audit opens every route in \`docs/agent-context/routes.json\` with the default demo data, scrolls the whole page so lazy images load, and inspects every visible image and video slot. To regenerate it:`);
w();
w("```sh");
w("npm run dev                                   # :5173");
w("node tests/e2e/media-audit.mjs 1512 --json audit-1512.json");
w("node tests/e2e/media-audit.mjs 1126 --json audit-1126.json");
w("node scripts/media/coverage-doc.mjs audit-1512.json audit-1126.json");
w("node tests/e2e/media-fallback.mjs              # failure handling and playback");
w("node tests/e2e/media-nested.mjs 1512           # nested tabs, threads and modals");
w("```");
w();
w("## Summary");
w();
w("| | " + ["Before", "1512×805", N && "1126×797"].filter((x) => x !== null && x !== undefined && (x !== "Before" || B)).join(" | ") + " |");
w("|---|" + "---|".repeat(1 + (N ? 1 : 0) + (B ? 1 : 0)));
const row = (label, k) => w(`| ${label} | ${[B?.[k], S[k], N?.[k]].filter((x, i) => (i === 0 ? !!B : i === 2 ? !!N : true)).join(" | ")} |`);
row("Routes audited", "routes");
row("Routes with no media issues", "clean");
row("Visible images", "images");
row("Video players", "players");
row("Empty media frames", "empty");
row("Generic avatar placeholders", "avatars");
row("Broken images", "broken");
row("Distorted (stretched) images", "stretched");
row("Images showing a failure fallback", "fallbacks");
row("Failed media requests", "failed");
row("Routes with horizontal overflow", "overflow");
w();
w("“Empty media frames” counts visible slots still marked as placeholders. Intentional empty states (below) are text-only by design and aren't counted as frames.");
w();

const issues = main.filter(issueCount);
w("## Unresolved issues");
w();
if (!issues.length && !(narrow ?? []).filter(issueCount).length) w("The audit found no media issues at either size. The known limitations are listed further down.");
for (const [label, rows] of [["1512", main], ["1126", narrow ?? []]]) for (const r of rows.filter((r) => r.overflow)) w(`- Layout, not media: **${r.id}** (\`${r.path}\`) scrolls sideways at ${label}. The Feed's right rail is copied from the reference, and this overflow was there before the media work (see \`src/pages/social/NOTES.md\`).`);
for (const [label, rows] of [["1512", main], ["1126", narrow ?? []]]) for (const r of rows.filter(issueCount)) w(`- **${r.id}** (${label}, \`${r.path}\`): ${[r.empty.length && `empty: ${r.empty.join(", ")}`, r.avatars && `${r.avatars} avatar placeholders`, r.broken.length && `broken: ${r.broken.join(", ")}`, r.stretched && `${r.stretched} stretched`, r.fallbacks && `${r.fallbacks} fallbacks`, r.failed.length && `failed: ${r.failed.join(", ")}`, r.noPoster && `${r.noPoster} videos without poster`].filter(Boolean).join("; ")}`);
w();

w("## Coverage by screen");
w();
w("Media per route at 1512×805. Slot is the nearest `data-testid`. Avatars and fan illustrations are counted, but they aren't listed file by file.");
w();
w("| Screen | Route | Images | Players | Files shown (slot → file) | Status |");
w("|---|---|---|---|---|---|");
for (const r of main) {
  const files = [...new Map(r.media.filter((m) => !/creators\/fans\//.test(m.src)).map((m) => [m.src, `${m.slot || "—"} → \`${m.src.replace(/^\/assets\//, "")}\``])).values()];
  const vids = (r.players ?? []).map((p) => `▶ \`${(p.poster || "").replace(/^\/assets\//, "")}\` (${p.state})`);
  const list = [...files.slice(0, 8), ...vids].join("<br>") + (files.length > 8 ? `<br>…+${files.length - 8} more` : "");
  const status = issueCount(r) ? "Issue" : r.images || r.players?.length ? "Populated" : "No media slots";
  w(`| ${esc(r.id)} | \`${esc(r.path)}\` | ${r.images} | ${r.players?.length ?? 0} | ${list || "—"} | ${status} |`);
}
w();

w("## Asset inventory");
w();
w("Every file is local under `public/assets/` and referenced by key through `src/media/assets.json` (built by `npm run media:catalog`). The mock store holds keys, never URLs, so the same item uses the same file everywhere.");
w();
w("| Key | File | Type | Source | Author | License | Resolution | Ratio |");
w("|---|---|---|---|---|---|---|---|");
for (const [k, c] of Object.entries(credits).sort(([a], [b]) => a.localeCompare(b))) {
  const type = /\.mp4$/.test(c.file) ? "video" : /\.svg$/.test(c.file) ? "SVG illustration" : c.source?.startsWith("original") ? "generated image" : "photo";
  const src = c.source?.startsWith("http") ? `[Commons](${c.source})` : esc(c.source);
  w(`| \`${k}\` | \`${c.file.replace(/^assets\//, "")}\` | ${type} | ${src} | ${esc(c.author)} | ${esc(c.license)} | ${c.width}×${c.height} | ${ratio(c.width, c.height)} |`);
}
w();

const videos = Object.entries(catalog).filter(([, a]) => /\.mp4$/.test(a.src));
w("## Playable clips");
w();
w("These are muted H.264 MP4 files, and each has a WebP poster and a duration badge. A clip starts only when the creator clicks play, and the player shows native controls. There are two exceptions, both copied from the reference. First, the Welcome modal plays the welcome clip muted when the modal opens, as TopFan's original does. Second, the Monetize video popup keeps the design's own controls (play/pause, ±15 s, seek, speed, mute and fullscreen), wired to the real file. The sequences listed as “original sequence” are slideshows made from the licensed photos above, not filmed footage. Livestream content is labeled “Recorded preview”.");
w();
w("| Key | Duration | Poster | Made from |");
w("|---|---|---|---|");
for (const [k, a] of videos) w(`| \`${k}\` | ${a.duration ? Math.round(a.duration) + " s" : "—"} | \`${(a.poster ?? "").replace(/^\/assets\//, "")}\` | ${esc(credits[k]?.title ? `${credits[k].title} (${credits[k].license})` : credits[k]?.source ?? "")} |`);
w();
const previews = new Set(main.flatMap((r) => (r.players ?? []).filter((p) => p.state === "video-preview").map((p) => `${r.id}: ${p.label || p.poster}`)));
w("## Preview-only frames");
w();
w(previews.size ? [...previews].map((x) => `- ${x}`).join("\n") : "None. Every video slot in the default demo has a playable file.");
w();
w("## Intentional empty states and fixtures");
w();
w("- Text and poll posts have no image, which is their design in TopFan.");
w("- Discount Codes stay text-based.");
w("- Empty lists (for example a search with no results) show TopFan's own empty-state copy.");
w("- Content Autopilot, missing photo: `?apFixture=missing-asset` removes the requested photo, so the draft shows “No photo yet” and is held. It is never replaced automatically. Run `tests/e2e/autopilot.mjs` (scenario C).");
w("- Content Autopilot, unapproved photo: `?apFixture=unapproved-asset` keeps the photo, but it isn't approved for posting yet. Run `tests/e2e/autopilot.mjs` (scenario C2).");
w("- Load failures: `tests/e2e/media-fallback.mjs` blocks files on purpose and checks three things:");
w("  - The content-type fallback (`public/assets/illustrations/fallback-*.svg`) replaces the file in a slot of the same size.");
w("  - No broken-image icon appears.");
w("  - The failure is logged to `window.__mediaErrors` and the console.");
w();
w("## Known limitations");
w();
w("- Photos come from Wikimedia Commons under CC0, public domain, CC BY or CC BY-SA. Attribution is in the inventory above. Before any public or commercial use, a person should review the licenses (CC BY-SA adaptations, crops in this case, carry share-alike terms).");
w("- No real, identifiable person stands in for a fictional creator or fan. Creator imagery is action/landscape photography or objects, and fans have original illustrated avatars.");
w("- Brands are fictional: Ridgeline, Northpeak, Summit Soda, Glacier Hydration and Corner Mart, with original SVG art. A few photos still show small incidental marks:");
w("  - An avalanche airbag pack shows the manufacturer's label (`posts/airbag-pack`).");
w("  - A helmet sticker reads a resort name (`posts/goggles`).");
w("- The video clips are short, muted demo loops (about 8 s). They aren't the creator's real footage.");
w("- Livestream content is labeled “Recorded preview”. The demo has no live video.");
w("- The default seed has no events, which is the spec default. For the event-detail route the audit adds the same sample event that the in-app Bandsintown import creates. Images on event cards appear once an event exists.");
w("- E-book covers (3:4) are center-cropped in the square store cards. The full cover shows on the product page.");
w("- Posts and chat media created during the demo through New Post or the message composer show the existing placeholder, because the mock upload stores only the file name. Nothing real is uploaded.");
w("- The Newsletter band on Home keeps its CSS gradient (the reference shows a stage photo there, and the demo has no suitable licensed photo).");
w("- The Monetize Single Video uses the vertical park reel, because that player is portrait. The episode and single clips are 5–8 s, and their listed durations match the files.");
w("- The audit covers each route's default state. Nested states are checked separately and aren't in the table above:");
w("  - `tests/e2e/media-nested.mjs`: Messages thread, tabs and modals; Insights lists; Wallet categories; refund detail; Fulfillment; Activity; Delegation.");
w("  - `tests/e2e/autopilot.mjs`: Autopilot draft media states.");
w("  - `tests/e2e/media-fallback.mjs`: failures and playback.");
w();
fs.writeFileSync(path.join(ROOT, "docs/media-coverage.md"), out.join("\n"));
console.log(`wrote docs/media-coverage.md (${main.length} routes, ${Object.keys(credits).length} assets, issues: ${issues.length})`);
